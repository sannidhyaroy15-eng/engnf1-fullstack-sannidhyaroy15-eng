// Helper to generate future UTC ISO slot times rounded to 30 mins
export function getRelativeIsoSlot(daysAhead: number, hour: number, minute: 0 | 30, durationMinutes: number) {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + daysAhead);
  d.setUTCHours(hour, minute, 0, 0);
  const start = d.toISOString();
  d.setUTCMinutes(d.getUTCMinutes() + durationMinutes);
  const end = d.toISOString();
  return { start, end };
}

